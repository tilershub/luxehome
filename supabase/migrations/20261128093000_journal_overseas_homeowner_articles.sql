## Why is renovating from abroad harder than it looks?

A bathroom is the most technical room in a house. In a few square metres you have water supply, waste drainage, venting, electrical wiring, waterproofing and tiling — and most of that work is covered up within days.

When you are overseas, three things usually go wrong:

- **Separate trades with no single owner.** A plumber, a tiler and a hardware shop each do their part, and nobody is responsible for the result.
- **Decisions made on site without you.** Tile layouts, niche positions and fixture heights get "decided" by whoever is there that day.
- **Hidden work with no record.** Once tiles go on, you cannot check whether the waterproofing reached the right height or whether pipes were pressure tested.

The fix is not to fly home for every stage. It is to choose a process where scope is fixed before work starts and hidden stages are documented.

## Step 1: Start with a short conversation

Send the property location, a few photos or a short video of the existing bathroom, and what you want to change. Mention your expected budget range and when you would like the work done.

A good company will tell you honestly whether the project makes sense before you pay anything. At LUXEhome, the first phone or WhatsApp conversation is free.

## Step 2: Arrange a measured site inspection

Nobody can price a bathroom properly from photos. Floor levels, wall condition, the existing drainage route and the water pressure all affect the design and the cost.

You only need someone to open the house — a parent, relative, neighbour or caretaker. The design team measures, photographs and checks the services, then talks you through what they found by video call.

> **Tip:** Ask for photos of the existing drainage points and any damp or leak marks. These are the details that change the price later.

## Step 3: Review a measured layout, 3D visuals and a written scope

This is the most important stage for overseas homeowners, because it replaces "seeing it in person".

Before you approve anything, you should receive:

- A **measured layout** showing where the shower, WC, vanity and door will go
- **3D visuals or a walkthrough video** so you can see the finished room
- A **named list of materials and fixtures** — brands and models, not "standard tiles"
- A **written construction scope** covering demolition, plumbing, electrical, waterproofing, tiling, ceiling and finishing
- A clear **payment schedule tied to stages**

Read every line. On one recent project, an owner living abroad only noticed after installation that the ceiling material in the proposal was different from what they had imagined. It was in the document — it just wasn't reviewed. Ten minutes on a video call reviewing the scope saves weeks of frustration.

## Step 4: Agree how you will communicate

Agree this before work starts, not during it:

- **One WhatsApp group** with you, the project lead and your local contact
- **Progress updates** at each stage, with photos and short videos
- **Approval points** where work stops until you say yes (tile setting-out, niche positions, glass design)
- **Time zones** — Sri Lanka is UTC+5:30, so a morning update in Colombo is evening in Melbourne and early morning in London

## Step 5: Watch the hidden stages closely

These are the stages you will never see again once the bathroom is finished. Ask for photo or video proof of each one.

| Stage | What you should see | Why it matters |
|---|---|---|
| Demolition | Bare walls and floor, old pipes removed | Shows the real condition before new work |
| Plumbing | New supply and waste lines, pressure test result | A leaking joint behind tiles is very costly to fix |
| Electrical | Wiring in conduit, safe positions away from water | Safety and future maintenance |
| Waterproofing | Membrane coats, wet zone up to full height | The single biggest cause of failed bathrooms |
| Flood test | Floor flooded and checked over about two days | Proves the floor holds water before tiling |
| Tiling | Setting-out, falls to the drain, grout lines | Poor falls leave standing water |

