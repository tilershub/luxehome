## A real example: our Nawala Airbnb bathroom

The owner of our [Nawala project](/projects/nawala-complete-bathroom-renovation) was renovating for Airbnb guests, with the goal of raising the value of the property. She lived abroad during construction and gave us full design freedom.

The existing bathroom had an angled wall and almost no separation between the shower and the rest of the room. Our main design decisions were:

- **Moving the door to the centre** and the vanity to the opposite wall, so the room works around the angle instead of fighting it
- **A curved 10 mm sandblasted glass partition** to separate the wet area while keeping the room open and private
- **80 × 80 cm tiles running to about eight feet high**, cut carefully around the angled wall, for fewer grout lines and a calm finish
- **A concealed cistern** for a cleaner look and easier cleaning
- **Two coats of waterproofing** in the wet and dry zones, followed by a flood test of about two days before tiling

Because the owner was overseas, every stage was shared on WhatsApp. When the tiles around the shower drain were set out of line, it was caught from the progress photos and corrected before the project moved on.

