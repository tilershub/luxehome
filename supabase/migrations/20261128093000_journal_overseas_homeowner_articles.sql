## Questions about the hidden work

### 8. How do you waterproof the shower area, and how high?

Ask which product is used, how many coats, and how high the membrane goes in the wet zone. On our projects, the wet area is typically waterproofed to around seven to eight feet with two coats.

### 9. Do you flood test before tiling?

A flood test keeps water on the waterproofed floor for a period — we usually allow about two days — to prove it holds before tiles go down.

### 10. Are new water lines pressure tested?

A leaking joint behind finished tiles is one of the most expensive problems to fix. Pressure testing finds it while the walls are still open.

### 11. Will you send photos and video of each hidden stage?

If the answer is anything less than a clear yes, keep looking.

