## What makes a bathroom renovation cost more?

### 1. Moving the layout

Keeping the WC and shower where they are is the cheapest option. Moving them means new drainage routes, floor breaking and re-levelling. Sometimes it is worth it — on our [Nawala Airbnb project](/projects/nawala-complete-bathroom-renovation) we moved the door to the centre and the vanity to the opposite wall, which completely changed how the room works.

### 2. Size and tile format

More wall area means more tiles, adhesive and labour. Large-format tiles (such as 80 × 80 cm) look seamless but need flatter walls and more careful cutting, especially on angled walls.

### 3. Fixtures and fittings

Concealed cisterns, wall-hung WCs, rain showers and thermostatic mixers cost more than standard pieces. The brand also matters. Ask for named brands and models in writing so you can compare like for like.

### 4. Shower glass

A straight 10 mm tempered glass panel is the standard choice. Curved, sandblasted or frameless designs cost more but can solve awkward layouts beautifully.

### 5. Hidden conditions

Old pipes, damp walls, weak screeds or poor drainage only appear after demolition. A good contractor tells you about the likely risks after inspection and explains how surprises will be priced before work starts.

## What makes a renovation cheaper?

- Keeping the existing layout and drainage points
- Choosing mid-range tiles with premium fixtures where you touch them every day (tap, shower, WC seat)
- Renovating two bathrooms at the same time, which shares site setup, labour and supervision
- Approving all selections before work starts, so nothing changes mid-project

## How do overseas homeowners usually pay?

Payments are normally made in stages tied to completed work — for example, a deposit on confirmation, then payments after milestones such as waterproofing and tiling, with a final payment on handover. Avoid paying the full amount upfront, and avoid paying individual tradesmen directly.

Because you are converting from AUD, GBP, EUR, USD or another currency, check the current exchange rate when you approve each stage. The quotation itself should be in LKR.

## How to compare quotations from abroad

Line up each quotation against the same checklist:

1. Is the scope written out stage by stage?
2. Are tile and fixture brands and models named?
3. Is waterproofing included, with a flood test?
4. Are plumbing pressure tests included?
5. Are ceiling, lighting and glass included?
6. Is debris removal and cleaning included?
7. Is there a written workmanship warranty?
8. How long is the quotation valid?

The lowest number is often the one with the most missing lines.

